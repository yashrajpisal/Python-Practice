

day = input("Enter day : ")

if day == "Mon" or day == "Monday":
    print("Start of the week")
elif day == "Fri" or day == "Friday":
    print("Weekend is coming")
elif day == "Sat" or day == "Saturday":
    print("Weekend Start")

elif day == "Sun" or day == "Sunday":
    print("Relax, it's Sunday")
else:
    print("Yet another day")
